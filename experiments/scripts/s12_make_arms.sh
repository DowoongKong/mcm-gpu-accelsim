#!/bin/bash
# Step 12 (docs/s12_d1l1_xlat_diag.ko.md): build the arm directories of the D1-L1 translation diagnosis.
# Every gpgpusim.config is the V3 ref config with whole-line substitutions only (plus the PCC cursor line),
# and each arm is checked to differ from its parent by exactly the intended lines.
# Usage: s12_make_arms.sh <arm> [<arm> ...]   arms: ref4k base4k_pcc ideal4k_pcc ref64k base64k_pcc ideal64k_pcc
#        smoke arms: smoke_par_base4k smoke_ser_base4k smoke_ser_ideal4k  (env SMOKE_CAP, default 50000000)
# Runs inside or outside the container; paths are the container view (/accel-sim).
set -euo pipefail
X=/accel-sim/llm_exp/experiments/deepseek_llama8b_b4s256_steps/s12_D1L1
H=${HOSTROOT:-/accel-sim}
XH=${X/#\/accel-sim/$H}
SRC=$H/llm_exp/experiments/v3_decode_S256/ref_batch4
SRC_MD5=608a40b4f2e77c77633fc983bb3b0678
TRACE=/accel-sim/llm_exp/traces/s10_deepseek_b4s256_steps/traces/kernelslist_D1-L1.g
FAST=/accel-sim/llm_exp/llm_sim_tree_fast
SERIAL=/accel-sim/llm_exp/llm_sim_tree_serial
SMOKE_CAP=${SMOKE_CAP:-50000000}
MAP=placement_batch4.map
die(){ echo "ABORT: $*" >&2; exit 1; }
md5(){ md5sum "$1" | awk '{print $1}'; }
[ "$(md5 $SRC/gpgpusim.config)" = $SRC_MD5 ] || die "V3 ref config md5 changed"
for l in "-gmmu_placement_dump ./$MAP" "-gpgpu_tlb_ideal 0" "-gpgpu_page_size_policy 0" "-gpgpu_max_insn 10000000000"; do
  [ "$(grep -cx -- "$l" $SRC/gpgpusim.config)" = 1 ] || die "V3 ref config lacks exactly one '$l'"
done
grep -qE '^-gpgpu_cta_chiplet_cursor[[:space:]]' $SRC/gpgpusim.config && die "V3 ref config already sets the PCC cursor"

# changed lines between two configs, as "<old>|<new>" / "+<added>" tokens
delta(){ { diff "$1" "$2" || true; } | { grep '^[<>]' || true; } | sort | tr '\n' ';'; }   # diff/grep exit 1 is not an error here
subst(){ sed "s|^$(printf '%s' "$2" | sed 's/[.[\*^$/]/\\&/g')\$|$3|" "$1"; }

make_cfg(){   # $1 arm -> writes $XH/$1/gpgpusim.config, echoes parent for the check
  local a=$1 d=$XH/$1; mkdir -p $d; cp $SRC/trace.config $SRC/config_ampere_islip.icnt $d/
  case $a in
    ref4k)        cp $SRC/gpgpusim.config $d/gpgpusim.config ;;
    ref64k)       subst $SRC/gpgpusim.config "-gpgpu_page_size_policy 0" "-gpgpu_page_size_policy 1" > $d/gpgpusim.config ;;
    base4k_pcc|smoke_par_base4k|smoke_ser_base4k)
                  { subst $SRC/gpgpusim.config "-gmmu_placement_dump ./$MAP" "-gmmu_placement_load ../ref4k/$MAP"; echo "-gpgpu_cta_chiplet_cursor 1"; } > $d/gpgpusim.config ;;
    ideal4k_pcc|smoke_ser_ideal4k)
                  { subst $SRC/gpgpusim.config "-gmmu_placement_dump ./$MAP" "-gmmu_placement_load ../ref4k/$MAP" \
                      | subst /dev/stdin "-gpgpu_tlb_ideal 0" "-gpgpu_tlb_ideal 1"; echo "-gpgpu_cta_chiplet_cursor 1"; } > $d/gpgpusim.config ;;
    base64k_pcc)  { subst $XH/ref64k/gpgpusim.config "-gmmu_placement_dump ./$MAP" "-gmmu_placement_load ../ref64k/$MAP"; echo "-gpgpu_cta_chiplet_cursor 1"; } > $d/gpgpusim.config ;;
    ideal64k_pcc) { subst $XH/ref64k/gpgpusim.config "-gmmu_placement_dump ./$MAP" "-gmmu_placement_load ../ref64k/$MAP" \
                      | subst /dev/stdin "-gpgpu_tlb_ideal 0" "-gpgpu_tlb_ideal 1"; echo "-gpgpu_cta_chiplet_cursor 1"; } > $d/gpgpusim.config ;;
    *) die "unknown arm $a" ;;
  esac
  case $a in smoke_*) sed -i "s|^-gpgpu_max_insn 10000000000\$|-gpgpu_max_insn $SMOKE_CAP|" $d/gpgpusim.config ;; esac
}

expect(){     # $1 arm: the exact line delta against the V3 ref config
  case $1 in
    ref4k)        echo "" ;;
    ref64k)       echo "< -gpgpu_page_size_policy 0;> -gpgpu_page_size_policy 1;" ;;
    base4k_pcc)   echo "< -gmmu_placement_dump ./$MAP;> -gmmu_placement_load ../ref4k/$MAP;> -gpgpu_cta_chiplet_cursor 1;" ;;
    ideal4k_pcc)  echo "< -gmmu_placement_dump ./$MAP;< -gpgpu_tlb_ideal 0;> -gmmu_placement_load ../ref4k/$MAP;> -gpgpu_cta_chiplet_cursor 1;> -gpgpu_tlb_ideal 1;" ;;
    base64k_pcc)  echo "< -gmmu_placement_dump ./$MAP;< -gpgpu_page_size_policy 0;> -gmmu_placement_load ../ref64k/$MAP;> -gpgpu_cta_chiplet_cursor 1;> -gpgpu_page_size_policy 1;" ;;
    ideal64k_pcc) echo "< -gmmu_placement_dump ./$MAP;< -gpgpu_page_size_policy 0;< -gpgpu_tlb_ideal 0;> -gmmu_placement_load ../ref64k/$MAP;> -gpgpu_cta_chiplet_cursor 1;> -gpgpu_page_size_policy 1;> -gpgpu_tlb_ideal 1;" ;;
    smoke_par_base4k|smoke_ser_base4k)
                  echo "< -gmmu_placement_dump ./$MAP;< -gpgpu_max_insn 10000000000;> -gmmu_placement_load ../ref4k/$MAP;> -gpgpu_cta_chiplet_cursor 1;> -gpgpu_max_insn $SMOKE_CAP;" ;;
    smoke_ser_ideal4k)
                  echo "< -gmmu_placement_dump ./$MAP;< -gpgpu_max_insn 10000000000;< -gpgpu_tlb_ideal 0;> -gmmu_placement_load ../ref4k/$MAP;> -gpgpu_cta_chiplet_cursor 1;> -gpgpu_max_insn $SMOKE_CAP;> -gpgpu_tlb_ideal 1;" ;;
  esac
}

write_run(){  # $1 arm $2 tree $3 threads
  cat > $XH/$1/run.sh <<EOF
#!/bin/bash
# s12_D1L1 arm $1 (generated by llm_exp/scripts/s12_make_arms.sh). Tree $2, threads $3, unpinned.
TREE=$2
TH=$3
TRACE=$TRACE
cd $X/$1
source \$TREE/gpu-simulator/setup_environment.sh release >/dev/null 2>&1
{ echo "step12 s12_D1L1 arm=$1 tree=\$TREE threads=\$TH trace=\$TRACE"; date
  md5sum \$TREE/gpu-simulator/bin/release/accel-sim.out \$GPGPUSIM_ROOT/lib/\$GPGPUSIM_CONFIG/libcudart.so gpgpusim.config trace.config config_ampere_islip.icnt \$TRACE
  ldd \$TREE/gpu-simulator/bin/release/accel-sim.out | grep -E 'cudart|gomp'
} > provenance.txt
export ACCELSIM_NO_PIN=1
t0=\$SECONDS
env OMP_NUM_THREADS=\$TH ACCELSIM_ALLOW_UNVERIFIED_THREADS=1 nice -n 10 \\
  \$TREE/gpu-simulator/bin/release/accel-sim.out \\
  -config ./gpgpusim.config -config ./trace.config -trace \$TRACE > run.log 2>&1
echo "EXIT=\$? SECONDS=\$((SECONDS-t0)) load=\$(cut -d' ' -f1 /proc/loadavg)" > exit_code.txt
EOF
  chmod +x $XH/$1/run.sh; }

for a in "$@"; do
  [ -e $XH/$a/run.log ] && die "$a already has run.log -- refusing to overwrite"
  make_cfg $a
  got=$(delta $SRC/gpgpusim.config $XH/$a/gpgpusim.config); want=$(expect $a | tr ';' '\n' | { grep -v '^$' || true; } | sort | tr '\n' ';')
  [ "$got" = "$want" ] || die "$a config delta mismatch: got [$got] want [$want]"
  case $a in *ser*|ideal4k_pcc|ideal64k_pcc) write_run $a $SERIAL 1 ;; *) write_run $a $FAST 8 ;; esac
  echo "OK $a  delta=[${got}]"
done
