#!/bin/bash
# Step 15 (docs/s15_chiplet_hash_apply.ko.md): build one arm that reruns an existing arm on the
# chiplet-hash trees, changing ONLY the partition-indexing lines of its config.
#   indexing 0 -> config copied unchanged (regression gate A2)
#   indexing 7 -> "-gpgpu_memory_partition_indexing 0" becomes 7, plus "-gpgpu_mem_hash_chiplets 4"
# The arm gets its own placement dump/load paths rewritten only if the source used ../ (see MAPDIR).
# Usage: s15_make_arm.sh <new arm dir> <source arm dir> <0|7> <fast|serial> <threads> <trace kernelslist> [MAPDIR]
#   paths are container paths under /accel-sim; MAPDIR (optional) replaces "../ref*/placement_batch4.map"
#   load paths with "MAPDIR/placement_batch4.map".
set -euo pipefail
H=${HOSTROOT:-/accel-sim}
NEW=$1; SRC=$2; IDX=$3; KIND=$4; TH=$5; TRACE=$6; MAPDIR=${7:-}
NEWH=${NEW/#\/accel-sim/$H}; SRCH=${SRC/#\/accel-sim/$H}
case $KIND in
  fast)   TREE=/accel-sim/llm_exp/llm_sim_tree_hash ;;
  serial) TREE=/accel-sim/llm_exp/llm_sim_tree_hash_serial ;;
  *) echo "ABORT: tree kind $KIND" >&2; exit 1 ;;
esac
die(){ echo "ABORT: $*" >&2; exit 1; }
[ -e $NEWH/run.log ] && die "$NEW already has run.log"
[ "$(grep -cx -- '-gpgpu_memory_partition_indexing 0' $SRCH/gpgpusim.config)" = 1 ] || die "source config lacks exactly one indexing-0 line"
mkdir -p $NEWH
cp $SRCH/trace.config $SRCH/config_ampere_islip.icnt $NEWH/
if [ "$IDX" = 7 ]; then
  sed 's|^-gpgpu_memory_partition_indexing 0$|-gpgpu_memory_partition_indexing 7\n-gpgpu_mem_hash_chiplets 4|' \
      $SRCH/gpgpusim.config > $NEWH/gpgpusim.config
  want="< -gpgpu_memory_partition_indexing 0;> -gpgpu_mem_hash_chiplets 4;> -gpgpu_memory_partition_indexing 7;"
elif [ "$IDX" = 0 ]; then
  cp $SRCH/gpgpusim.config $NEWH/gpgpusim.config; want=""
else die "indexing must be 0 or 7"; fi
if [ -n "$MAPDIR" ]; then
  sed -i "s|^-gmmu_placement_load .*placement_batch4.map\$|-gmmu_placement_load $MAPDIR/placement_batch4.map|" $NEWH/gpgpusim.config
fi
got=$( { diff $SRCH/gpgpusim.config $NEWH/gpgpusim.config || true; } | { grep '^[<>]' || true; } | { grep -v 'placement_load' || true; } | sort | tr '\n' ';')
want=$(printf '%s' "$want" | tr ';' '\n' | { grep -v '^$' || true; } | sort | tr '\n' ';')
[ "$got" = "$want" ] || die "config delta mismatch: got [$got] want [$want]"
cat > $NEWH/run.sh <<EOF
#!/bin/bash
# s15 arm (generated by llm_exp/scripts/s15_make_arm.sh): source $SRC, indexing $IDX, tree $TREE, threads $TH.
TREE=$TREE
TRACE=$TRACE
cd $NEW
source \$TREE/gpu-simulator/setup_environment.sh release >/dev/null 2>&1
{ echo "step15 arm=$NEW src=$SRC indexing=$IDX tree=\$TREE threads=$TH trace=\$TRACE"; date
  md5sum \$TREE/gpu-simulator/bin/release/accel-sim.out \$GPGPUSIM_ROOT/lib/\$GPGPUSIM_CONFIG/libcudart.so gpgpusim.config trace.config config_ampere_islip.icnt \$TRACE
} > provenance.txt
export ACCELSIM_NO_PIN=1
t0=\$SECONDS
env OMP_NUM_THREADS=$TH ACCELSIM_ALLOW_UNVERIFIED_THREADS=1 nice -n 10 \\
  \$TREE/gpu-simulator/bin/release/accel-sim.out -config ./gpgpusim.config -config ./trace.config -trace \$TRACE > run.log 2>&1
echo "EXIT=\$? SECONDS=\$((SECONDS-t0)) load=\$(cut -d' ' -f1 /proc/loadavg)" > exit_code.txt
EOF
chmod +x $NEWH/run.sh
echo "OK $NEW idx=$IDX tree=$KIND th=$TH delta=[$got]"
