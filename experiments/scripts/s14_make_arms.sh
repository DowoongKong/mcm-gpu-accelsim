#!/bin/bash
# Step 14 (docs/s14_bw_microbench.ko.md): build the arms of the bandwidth microbenchmark.
# Every gpgpusim.config is the step-12 ref4k config (= V3 ref config, first-touch dump) with whole-line
# substitutions only, and each arm is checked to differ from it by exactly the intended lines.
#   ideal: 4 KB pages, -gpgpu_tlb_ideal 1   (serial tree; the OpenMP build refuses ideal TLB)
#   p64k : 64 KB pages
#   p4k  : 4 KB pages (unchanged config)
# Usage: s14_make_arms.sh <arm> [<arm> ...]
set -euo pipefail
H=${HOSTROOT:-/accel-sim}
SRC=$H/llm_exp/experiments/deepseek_llama8b_b4s256_steps/s12_D1L1/ref4k
X=/accel-sim/llm_exp/experiments/s14_bw_microbench
XH=${X/#\/accel-sim/$H}
TRACE=/accel-sim/llm_exp/traces/s14_bw_microbench/traces/kernelslist.g
FAST=/accel-sim/llm_exp/llm_sim_tree_fast
SERIAL=/accel-sim/llm_exp/llm_sim_tree_serial
die(){ echo "ABORT: $*" >&2; exit 1; }
for l in "-gpgpu_tlb_ideal 0" "-gpgpu_page_size_policy 0" "-gpgpu_max_insn 10000000000" \
         "-gpgpu_memory_partition_indexing 0" "-gpgpu_lasp_policy 3" "-gpgpu_lasp_chunk_size 4" "-gpgpu_n_chiplets 4"; do
  [ "$(grep -cx -- "$l" $SRC/gpgpusim.config)" = 1 ] || die "source config lacks exactly one '$l'"
done
subst(){ sed "s|^$(printf '%s' "$2" | sed 's/[.[\*^$/]/\\&/g')\$|$3|" "$1"; }
delta(){ { diff "$1" "$2" || true; } | { grep '^[<>]' || true; } | sort | tr '\n' ';'; }

for a in "$@"; do
  d=$XH/$a; [ -e $d/run.log ] && die "$a already has run.log -- refusing to overwrite"
  mkdir -p $d; cp $SRC/trace.config $SRC/config_ampere_islip.icnt $d/
  case $a in
    ideal) subst $SRC/gpgpusim.config "-gpgpu_tlb_ideal 0" "-gpgpu_tlb_ideal 1" > $d/gpgpusim.config
           want="< -gpgpu_tlb_ideal 0;> -gpgpu_tlb_ideal 1;"; TREE=$SERIAL; TH=1 ;;
    p64k)  subst $SRC/gpgpusim.config "-gpgpu_page_size_policy 0" "-gpgpu_page_size_policy 1" > $d/gpgpusim.config
           want="< -gpgpu_page_size_policy 0;> -gpgpu_page_size_policy 1;"; TREE=$FAST; TH=8 ;;
    p4k)   cp $SRC/gpgpusim.config $d/gpgpusim.config; want=""; TREE=$FAST; TH=8 ;;
    *) die "unknown arm $a" ;;
  esac
  got=$(delta $SRC/gpgpusim.config $d/gpgpusim.config)
  [ "$got" = "$want" ] || die "$a config delta mismatch: got [$got] want [$want]"
  cat > $d/run.sh <<EOF
#!/bin/bash
# s14 bandwidth microbenchmark arm $a (generated by llm_exp/scripts/s14_make_arms.sh). Tree $TREE, threads $TH.
TREE=$TREE
TRACE=$TRACE
cd $X/$a
source \$TREE/gpu-simulator/setup_environment.sh release >/dev/null 2>&1
{ echo "step14 arm=$a tree=\$TREE threads=$TH trace=\$TRACE"; date
  md5sum \$TREE/gpu-simulator/bin/release/accel-sim.out gpgpusim.config trace.config config_ampere_islip.icnt \$TRACE
} > provenance.txt
export ACCELSIM_NO_PIN=1
t0=\$SECONDS
env OMP_NUM_THREADS=$TH ACCELSIM_ALLOW_UNVERIFIED_THREADS=1 nice -n 10 \\
  \$TREE/gpu-simulator/bin/release/accel-sim.out -config ./gpgpusim.config -config ./trace.config -trace \$TRACE > run.log 2>&1
echo "EXIT=\$? SECONDS=\$((SECONDS-t0)) load=\$(cut -d' ' -f1 /proc/loadavg)" > exit_code.txt
EOF
  chmod +x $d/run.sh
  echo "OK $a delta=[$got] tree=$TREE threads=$TH"
done
