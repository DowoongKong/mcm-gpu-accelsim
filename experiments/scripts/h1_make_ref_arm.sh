#!/bin/bash
# Build the reference-run arm (sim/ref_mcm + sim/launch_ref.sh) of one hypothesis-1 trace directory
# llm_hypothesis1/<model>/<config>/ (docs/h1_llama70b_decode_batch_sweep.ko.md section 9). Nothing is launched.
#   config  = the 2026-11-04 70B 64 KiB distributed ref_mcm gpgpusim.config, instruction cap decided from the capture:
#             warp x 32 < 1e10 -> standard "-gpgpu_max_insn 10000000000" (cap line + its comment changed, diff = 4 lines),
#             else                -> source config verbatim (cap 0) + CAP_EXCEPTION.txt recording the user's instruction.
#   run.sh  = child shell without set -u (setup_environment.sh reads undefined variables).
#   launch  = h1_ref_launch_template.sh with the placeholders filled (gate on the chain's S6 check, preflight, run).
# Usage: h1_make_ref_arm.sh <model dir name> <config dir name> ["<user instruction text for a cap exception>"]
set -u
MODEL=$1; CFG=$2; WHY=${3:-"the user's instruction of 2026-11-09 (\"llama 70B batch 4랑 batch 16, 64, 256, 1024도 ref run을 순서대로 돌리되\")"}
H=/home/user/accel-sim-docker/llm_exp
P=$H/llm_hypothesis1/$MODEL/$CFG
SRC=$H/experiments_distributed/llama70b_b4s256_L1seq64k_mcm/ref_mcm
X=$P/sim/ref_mcm
die(){ echo "ABORT: $*" >&2; exit 1; }
[ -s $P/capture_info.json ] || die "$P/capture_info.json missing (capture not finished)"
[ -s $P/traces/kernelslist.g ] || die "$P/traces/kernelslist.g missing (post-processing not finished)"
[ -e $X/run.log ] && die "$X/run.log exists -- refusing to rebuild a run arm"
[ "$(md5sum $SRC/gpgpusim.config | cut -c1-32)" = 38ec08a8e4f8abfbae3bc0e1260508d1 ] || die "source ref_mcm config changed"
read -r FIRST LAST NK WARP < <(python3 -c "
import json; j=json.load(open('$P/capture_info.json')); print(j['window'][0], j['window'][1], j['n_window_kernels'], j['window_warp_insts'])")
COPIES=$(grep -c '^MemcpyHtoD,' $P/traces/kernelslist.g)
[ "$(grep -vc '^MemcpyHtoD,' $P/traces/kernelslist.g)" = "$NK" ] || die "kernelslist.g kernel count != capture window"
MINCOPIES=$(( COPIES - COPIES / 10 ))
CHECKLOG=h1_check_traces_${FIRST}_${LAST}.log
mkdir -p $X
cp $SRC/trace.config $SRC/config_ampere_islip.icnt $X/
if [ $(( WARP * 32 )) -lt 10000000000 ]; then
  CAP=10000000000; EXPECT_DIFF=4
  sed "s|^-gpgpu_max_insn 0\$|-gpgpu_max_insn 10000000000|; s|^# instruction cap: 0 = none (LLM exception agreed earlier; the RR L1seq arms also ran uncapped)\$|# instruction cap: standard 1e10 ($CFG: $WARP warp insn x 32 = $(( WARP * 32 )) thread insn < 1e10, no exception needed)|" \
    $SRC/gpgpusim.config > $X/gpgpusim.config
  rm -f $X/CAP_EXCEPTION.txt
else
  CAP=0; EXPECT_DIFF=0
  cp $SRC/gpgpusim.config $X/gpgpusim.config
  cat > $X/CAP_EXCEPTION.txt <<EOT
Instruction cap exception (-gpgpu_max_insn 0) for llm_hypothesis1/$MODEL/$CFG/sim/ref_mcm, recorded $(date '+%F') by Claude on
$WHY, under the standing 2026-09-19 b4s256 rule: this piece's stats warp count $WARP x 32 = $(( WARP * 32 )) thread
instructions exceeds the 1e10 cap, which would truncate the decode layer; the 70B L1seq distributed arms ran uncapped for the same reason.
If this exception is not intended, delete this file before launching (launch_ref.sh then refuses to start).
EOT
fi
[ "$(diff $SRC/gpgpusim.config $X/gpgpusim.config | grep -c '^[<>]')" = $EXPECT_DIFF ] || die "config delta is not the expected $EXPECT_DIFF lines"
cat > $X/run.sh <<EOF
#!/bin/bash
# h1 $MODEL/$CFG / ref_mcm: decode layer 0 of one all-decode step, 64 KiB pages, KERNEL_PARTITION + per-chiplet cursors +
# L2 TLB set hash 1, L1 TLB 64K 32 entries, L2 TLB 64K 1024 entries, merge caps unlimited, instruction cap $CAP.
# Child shell of ../launch_ref.sh (no set -u here: setup_environment.sh reads undefined variables, the 2026-09-12 launcher defect).
# Generated by llm_exp/scripts/h1_make_ref_arm.sh.
TREE=/accel-sim/llm_exp/llm_sim_tree_pwcstat_l1fwd
TH=\${TH:-16}
TRACE=/accel-sim/llm_exp/llm_hypothesis1/$MODEL/$CFG/traces/kernelslist.g
cd /accel-sim/llm_exp/llm_hypothesis1/$MODEL/$CFG/sim/ref_mcm
source \$TREE/gpu-simulator/setup_environment.sh release >/dev/null 2>&1
{ echo "h1 $CFG arm=ref_mcm tree=\$TREE threads=\$TH trace=\$TRACE max_insn=$CAP"; date
  md5sum \$TREE/gpu-simulator/bin/release/accel-sim.out \$GPGPUSIM_ROOT/lib/\$GPGPUSIM_CONFIG/libcudart.so gpgpusim.config trace.config config_ampere_islip.icnt \$TRACE
  ldd \$TREE/gpu-simulator/bin/release/accel-sim.out | grep cudart
} > provenance.txt
export ACCELSIM_NO_PIN=1
t0=\$SECONDS
env OMP_NUM_THREADS=\$TH ACCELSIM_ALLOW_UNVERIFIED_THREADS=1 nice -n 10 \\
  \$TREE/gpu-simulator/bin/release/accel-sim.out -config ./gpgpusim.config -config ./trace.config -trace \$TRACE > run.log 2>&1
echo "EXIT=\$? SECONDS=\$((SECONDS-t0)) load=\$(cut -d' ' -f1 /proc/loadavg)" > exit_code.txt
EOF
chmod +x $X/run.sh
sed -e "s|@MODEL@|$MODEL|g" -e "s|@CFG@|$CFG|g" -e "s|@NK@|$NK|g" -e "s|@MINCOPIES@|$MINCOPIES|g" \
    -e "s|@CHECKLOG@|$CHECKLOG|g" -e "s|@CAP@|$CAP|g" -e "s|@EXPECT_DIFF@|$EXPECT_DIFF|g" \
    $H/scripts/h1_ref_launch_template.sh > $P/sim/launch_ref.sh
chmod +x $P/sim/launch_ref.sh
bash -n $P/sim/launch_ref.sh && bash -n $X/run.sh || die "generated scripts do not parse"
echo "OK $MODEL/$CFG: kernels=$NK copies=$COPIES warp=$WARP cap=$CAP expect_diff=$EXPECT_DIFF check=$CHECKLOG cfg_md5=$(md5sum $X/gpgpusim.config | cut -c1-32)"
