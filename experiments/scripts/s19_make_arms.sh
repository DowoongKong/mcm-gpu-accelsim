#!/bin/bash
# Step 19 (docs/s19_mem_latency_microbench.ko.md): build the simulation arms of the memory-latency microbenchmark.
# Every gpgpusim.config is the V3 reference config (llm_exp/experiments/v3_decode_S256/ref_batch4: first-touch
# placement dump, RR batch-4, 4 KB pages, real TLB, cap 1e10) with whole-line substitutions only, and each arm is
# checked to differ from that source by exactly the intended lines.
#   ideal : -gpgpu_tlb_ideal 1           (llm_sim_tree_serial, 1 thread: the OpenMP build refuses an ideal TLB)
#   p64k  : -gpgpu_page_size_policy 1    (llm_sim_tree_pwcstat_l1fwd, 8 threads)
#   p4k   : unchanged page policy        (same tree, 8 threads)
# TLB variant (second argument, default v3):
#   v3  : TLB lines as in the V3 config (L1 64K 16 entries / L2 64K 512 / merge caps 192 and 46)
#   70b : the 2026-11-04 settings of the Llama-70B distributed set (L1 64K 32 entries + MSHR 32, L2 64K 1024 entries,
#         every TLB merge cap 1000000) -- applied to p64k and p4k only; the ideal arm has no TLB.
# Usage: s19_make_arms.sh <arm> [<arm> ...] [tlb=v3|tlb=70b]
set -euo pipefail
H=${HOSTROOT:-/home/user/accel-sim-docker}
SRC=$H/llm_exp/experiments/v3_decode_S256/ref_batch4
X=/accel-sim/llm_exp/experiments/s19_lat_microbench
XH=${X/#\/accel-sim/$H}
TRACE=/accel-sim/llm_exp/traces/s19_lat_microbench/traces/kernelslist.g
FAST=/accel-sim/llm_exp/llm_sim_tree_pwcstat_l1fwd
SERIAL=/accel-sim/llm_exp/llm_sim_tree_serial
die(){ echo "ABORT: $*" >&2; exit 1; }
TLB=v3; ARMS=()
for a in "$@"; do case $a in tlb=*) TLB=${a#tlb=} ;; *) ARMS+=("$a") ;; esac; done
[ "$TLB" = v3 ] || [ "$TLB" = 70b ] || die "tlb must be v3 or 70b"
for l in "-gpgpu_tlb_ideal 0" "-gpgpu_page_size_policy 0" "-gpgpu_max_insn 10000000000" "-gpgpu_l1_tlb_64k_assoc 16" \
         "-gpgpu_l1_tlb_64k_mshr_entries 16" "-gpgpu_l2_tlb_64k_sets 64" "-gpgpu_lasp_policy 3" "-gpgpu_n_chiplets 4"; do
  [ "$(grep -cx -- "$l" $SRC/gpgpusim.config)" = 1 ] || die "source config lacks exactly one '$l'"
done
subst(){ sed "s|^$(printf '%s' "$2" | sed 's/[.[\*^$/]/\\&/g')\$|$3|" "$1"; }
delta(){ { diff "$1" "$2" || true; } | { grep '^[<>]' || true; } | sort | tr '\n' ';'; }
TLB70B=("-gpgpu_l1_tlb_64k_assoc 16|-gpgpu_l1_tlb_64k_assoc 32" "-gpgpu_l1_tlb_64k_mshr_entries 16|-gpgpu_l1_tlb_64k_mshr_entries 32"
        "-gpgpu_l2_tlb_64k_sets 64|-gpgpu_l2_tlb_64k_sets 128"
        "-gpgpu_l1_tlb_4k_mshr_max_merge 192|-gpgpu_l1_tlb_4k_mshr_max_merge 1000000" "-gpgpu_l1_tlb_64k_mshr_max_merge 192|-gpgpu_l1_tlb_64k_mshr_max_merge 1000000"
        "-gpgpu_l1_tlb_2m_mshr_max_merge 192|-gpgpu_l1_tlb_2m_mshr_max_merge 1000000" "-gpgpu_l2_tlb_mshr_max_merge 46|-gpgpu_l2_tlb_mshr_max_merge 1000000"
        "-gpgpu_l2_tlb_64k_mshr_max_merge 46|-gpgpu_l2_tlb_64k_mshr_max_merge 1000000" "-gpgpu_l2_tlb_2m_mshr_max_merge 46|-gpgpu_l2_tlb_2m_mshr_max_merge 1000000")
apply_tlb(){ # $1 in, $2 out: apply the 70b TLB lines (or copy for v3); echo the expected delta fragment
  local cur=$1 tmp want=""
  if [ "$TLB" = 70b ]; then
    for pair in "${TLB70B[@]}"; do
      tmp=$(mktemp); subst "$cur" "${pair%%|*}" "${pair##*|}" > $tmp; [ "$cur" != "$1" ] && rm -f "$cur"; cur=$tmp
      want="$want< ${pair%%|*};> ${pair##*|};"
    done
  fi
  cp "$cur" "$2"; [ "$cur" != "$1" ] && rm -f "$cur"; printf '%s' "$want"
}
for a in "${ARMS[@]}"; do
  d=$XH/$a; [ -e $d/run.log ] && die "$a already has run.log -- refusing to overwrite"
  mkdir -p $d; cp $SRC/trace.config $SRC/config_ampere_islip.icnt $d/
  case $a in
    ideal) subst $SRC/gpgpusim.config "-gpgpu_tlb_ideal 0" "-gpgpu_tlb_ideal 1" > $d/gpgpusim.config
           want="< -gpgpu_tlb_ideal 0;> -gpgpu_tlb_ideal 1;"; TREE=$SERIAL; TH=1 ;;
    p64k)  tmp=$(mktemp); subst $SRC/gpgpusim.config "-gpgpu_page_size_policy 0" "-gpgpu_page_size_policy 1" > $tmp
           want="< -gpgpu_page_size_policy 0;> -gpgpu_page_size_policy 1;$(apply_tlb $tmp $d/gpgpusim.config)"; TREE=$FAST; TH=8 ;;
    p4k)   want="$(apply_tlb $SRC/gpgpusim.config $d/gpgpusim.config)"; TREE=$FAST; TH=8 ;;
    *) die "unknown arm $a" ;;
  esac
  got=$(delta $SRC/gpgpusim.config $d/gpgpusim.config)
  [ "$got" = "$(printf '%s' "$want" | tr ';' '\n' | sort | tr '\n' ';')" ] || die "$a config delta mismatch: got [$got] want [$want]"
  cat > $d/run.sh <<EOF
#!/bin/bash
# s19 memory-latency microbenchmark arm $a, TLB variant $TLB (generated by llm_exp/scripts/s19_make_arms.sh). Tree $TREE, threads $TH.
TREE=$TREE
TRACE=$TRACE
cd $X/$a
source \$TREE/gpu-simulator/setup_environment.sh release >/dev/null 2>&1
{ echo "step19 arm=$a tlb=$TLB tree=\$TREE threads=$TH trace=\$TRACE"; date
  md5sum \$TREE/gpu-simulator/bin/release/accel-sim.out gpgpusim.config trace.config config_ampere_islip.icnt \$TRACE
} > provenance.txt
export ACCELSIM_NO_PIN=1
t0=\$SECONDS
env OMP_NUM_THREADS=$TH ACCELSIM_ALLOW_UNVERIFIED_THREADS=1 nice -n 10 \\
  \$TREE/gpu-simulator/bin/release/accel-sim.out -config ./gpgpusim.config -config ./trace.config -trace \$TRACE > run.log 2>&1
echo "EXIT=\$? SECONDS=\$((SECONDS-t0)) load=\$(cut -d' ' -f1 /proc/loadavg)" > exit_code.txt
EOF
  chmod +x $d/run.sh
  echo "OK $a tlb=$TLB delta=[$got] tree=$TREE threads=$TH"
done
