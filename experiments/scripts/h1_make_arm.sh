#!/bin/bash
# Build a measurement arm (base_mcm or ptwhop0_mcm) next to an existing ref_mcm arm of one hypothesis-1 trace directory
# (docs/h1_llama70b_decode_batch_sweep.ko.md section 10). Nothing is launched.
#   base_mcm    = ref_mcm/gpgpusim.config with "-gmmu_placement_dump ./placement_mcm.map" -> "-gmmu_placement_load ../ref_mcm/placement_mcm.map"
#   ptwhop0_mcm = base_mcm config + "-icnt_ptw_ring_hop_latency 0"
# The instruction cap (and CAP_EXCEPTION.txt) is inherited from ref_mcm. run.sh is a child shell without set -u.
# Usage: h1_make_arm.sh <model dir name> <config dir name> <base_mcm|ptwhop0_mcm>
set -u
MODEL=$1; CFG=$2; ARM=$3
H=/home/user/accel-sim-docker/llm_exp
P=$H/llm_hypothesis1/$MODEL/$CFG
REF=$P/sim/ref_mcm
X=$P/sim/$ARM
die(){ echo "ABORT: $*" >&2; exit 1; }
[ "$ARM" = base_mcm ] || [ "$ARM" = ptwhop0_mcm ] || die "arm must be base_mcm or ptwhop0_mcm"
[ -s $REF/gpgpusim.config ] || die "$REF/gpgpusim.config missing (build ref_mcm first)"
[ -e $X/run.log ] && die "$X/run.log exists -- refusing to rebuild a run arm"
grep -qx -- '-gmmu_placement_dump ./placement_mcm.map' $REF/gpgpusim.config || die "ref config does not dump ./placement_mcm.map"
mkdir -p $X
cp $REF/trace.config $REF/config_ampere_islip.icnt $X/
sed 's|^-gmmu_placement_dump ./placement_mcm.map$|-gmmu_placement_load ../ref_mcm/placement_mcm.map|' $REF/gpgpusim.config > $X/gpgpusim.config
if [ "$ARM" = ptwhop0_mcm ]; then echo "-icnt_ptw_ring_hop_latency 0" >> $X/gpgpusim.config; HOP=0; EXPECT=3; else HOP=-1; EXPECT=2; fi
[ "$(diff $REF/gpgpusim.config $X/gpgpusim.config | grep -c '^[<>]')" = $EXPECT ] || die "config delta is not $EXPECT lines"
if grep -qx -- '-gpgpu_max_insn 0' $X/gpgpusim.config; then
  [ -s $REF/CAP_EXCEPTION.txt ] || die "ref has cap 0 but no CAP_EXCEPTION.txt"
  { echo "Inherited from ../ref_mcm/CAP_EXCEPTION.txt (same trace, same cap rule):"; cat $REF/CAP_EXCEPTION.txt; } > $X/CAP_EXCEPTION.txt
fi
CAP=$(grep -x -- '-gpgpu_max_insn [0-9]*' $X/gpgpusim.config | awk '{print $2}')
cat > $X/run.sh <<EOF
#!/bin/bash
# h1 $MODEL/$CFG / $ARM: ref_mcm config + placement load from ../ref_mcm/placement_mcm.map$( [ "$ARM" = ptwhop0_mcm ] && echo " + PTW ring hop latency 0"), cap $CAP.
# Child shell of ../launch_$ARM.sh (no set -u: setup_environment.sh reads undefined variables). Generated by llm_exp/scripts/h1_make_arm.sh.
TREE=/accel-sim/llm_exp/llm_sim_tree_pwcstat_l1fwd
TH=\${TH:-16}
TRACE=/accel-sim/llm_exp/llm_hypothesis1/$MODEL/$CFG/traces/kernelslist.g
cd /accel-sim/llm_exp/llm_hypothesis1/$MODEL/$CFG/sim/$ARM
source \$TREE/gpu-simulator/setup_environment.sh release >/dev/null 2>&1
{ echo "h1 $CFG arm=$ARM tree=\$TREE threads=\$TH trace=\$TRACE max_insn=$CAP"; date
  md5sum \$TREE/gpu-simulator/bin/release/accel-sim.out \$GPGPUSIM_ROOT/lib/\$GPGPUSIM_CONFIG/libcudart.so gpgpusim.config trace.config config_ampere_islip.icnt \$TRACE ../ref_mcm/placement_mcm.map
  ldd \$TREE/gpu-simulator/bin/release/accel-sim.out | grep cudart
} > provenance.txt
export ACCELSIM_NO_PIN=1
t0=\$SECONDS
env OMP_NUM_THREADS=\$TH ACCELSIM_ALLOW_UNVERIFIED_THREADS=1 nice -n 10 \\
  \$TREE/gpu-simulator/bin/release/accel-sim.out -config ./gpgpusim.config -config ./trace.config -trace \$TRACE > run.log 2>&1
echo "EXIT=\$? SECONDS=\$((SECONDS-t0)) load=\$(cut -d' ' -f1 /proc/loadavg)" > exit_code.txt
EOF
chmod +x $X/run.sh
sed -e "s|@MODEL@|$MODEL|g" -e "s|@CFG@|$CFG|g" -e "s|@ARM@|$ARM|g" -e "s|@EXPECT_HOP@|$HOP|g" \
    $H/scripts/h1_arm_launch_template.sh > $P/sim/launch_$ARM.sh
chmod +x $P/sim/launch_$ARM.sh
bash -n $P/sim/launch_$ARM.sh && bash -n $X/run.sh || die "generated scripts do not parse"
echo "OK $MODEL/$CFG/$ARM: cap=$CAP diff_lines=$EXPECT cfg_md5=$(md5sum $X/gpgpusim.config | cut -c1-32)"
